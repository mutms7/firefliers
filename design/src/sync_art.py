# Copies the art from design/src into index.html as one self-contained module, `ART`.
# Edit the design sources, then run this from the repo root:  python design/src/sync_art.py
import os
D = os.path.dirname(os.path.abspath(__file__))
src = ''.join(open(os.path.join(D, f), encoding='utf-8').read() + '\n' for f in ['core.js', 'chars.js', 'props.js', 'tiles.js', 'icons.js', 'fx.js', 'ui.js', 'big.js', 'tree.js', 'hubwalk.js'])
block = ('/* ART:BEGIN generated by design/src/sync_art.py from design/src. Edit those files and rerun it; do not edit here. */\n'
         'const ART = (() => {\n' + src +
         'return { BUGS, FIREFLY, WEAPON_ICONS, EVOLVED_ICONS, PASSIVE_ICONS, PICKUPS, SPARKS, ICO, PLAYER_SHOTS, ENEMY_SHOTS, RUN_TILES, STUMP, STANDING, DEAD_LAMP, flipX, px, halo, pg, ell, bake, kitCSS, AMBER, AMBER_SMALL, AMBER_PILE, BR, TREE, NODE, badge, treeArt, treeAt, TREE_W, TREE_H, mountHaven, NPC_ART, SILHOUETTE, BUG_NAMES };\n'
         '})();\n/* ART:END */\n')
p = 'index.html'; s = open(p, encoding='utf-8').read()
if '/* ART:BEGIN' in s:
    i = s.index('/* ART:BEGIN'); j = s.index('/* ART:END */\n') + len('/* ART:END */\n'); s = s[:i] + block + s[j:]
else:
    anchor = '/* ---------- render ---------- */\n'; assert s.count(anchor) == 1; s = s.replace(anchor, anchor + block)
open(p, 'w', encoding='utf-8').write(s)
print('art module', len(block) // 1024, 'KB')
